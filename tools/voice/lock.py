"""Regenerate addon/car_review/voice-requirements.txt: every package the helper's Python needs,
pinned to an exact version with SHA-256 hashes for every platform, so voice setup installs
exactly what was tested and refuses anything else.

    python tools/voice/lock.py --uv path/to/uv

Needs uv (https://docs.astral.sh/uv/). num2words is added separately with --no-deps: its only
dependency (docopt) is for its command line, which isn't used, and has no wheel.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = Path(__file__).with_name("requirements.in")
OUT = ROOT / "addon" / "car_review" / "voice-requirements.txt"
NO_DEPS = {"num2words": "0.5.14"}

HEADER = """\
# Generated by tools/voice/lock.py from tools/voice/requirements.in. Don't edit by hand.
# Installed by voice setup with: uv pip install --require-hashes --no-deps --only-binary :all:
"""


def pypi_hashes(name: str, version: str) -> list[str]:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=60) as r:
        info = json.load(r)
    return [f["digests"]["sha256"] for f in info["urls"] if f["packagetype"] == "bdist_wheel"]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--uv", default="uv")
    args = ap.parse_args()
    result = subprocess.run(
        [args.uv, "pip", "compile", str(SOURCE), "--universal", "--python-version", "3.12", "--only-binary", ":all:",
         "--generate-hashes", "--no-header", "--no-annotate", "--quiet"],
        capture_output=True, text=True, check=True)
    lines = [HEADER, result.stdout.rstrip()]
    for name, version in NO_DEPS.items():
        hashes = pypi_hashes(name, version)
        if not hashes:
            sys.exit(f"{name} {version} has no wheel")
        lines.append(f"{name}=={version} \\\n" + " \\\n".join(f"    --hash=sha256:{h}" for h in hashes))
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
